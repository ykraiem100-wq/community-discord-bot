'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'dos-bot-smoke-'));
process.env.DATA_DIR = dir;
const db = require('../src/database');
try {
  const guild = 'guild-test';
  const user = 'user-test';
  assert.equal(db.ensureMember(guild, user).coins, 0);
  let result = db.addXp(guild, user, 'text', 250, { message: true });
  assert.equal(result.member.coins, 1);
  assert.equal(result.member.text_xp, 250);
  assert.equal(result.member.messages, 1);
  result = db.addXp(guild, user, 'voice', 9, { seconds: 60 });
  assert.equal(result.member.voice_xp, 9);
  assert.equal(result.member.total_xp, 259);
  const order = db.createPurchase(guild, user, 'legacy-test', 'Legacy item', 1);
  assert.ok(order > 0);
  assert.equal(db.ensureMember(guild, user).coins, 0);
  assert.equal(db.reviewOrder(guild, order, 'rejected', 'admin'), true);
  assert.equal(db.ensureMember(guild, user).coins, 1);
  assert.equal(db.reviewOrder(guild, order, 'rejected', 'admin'), false);
  assert.equal(db.leaderboard(guild, 'text')[0].score, 250);
  assert.equal(db.leaderboard(guild, 'voice')[0].score, 9);
  assert.equal(db.leaderboard(guild, 'coins')[0].score, 1);
  db.setSetting(guild, 'shop_channel_id', 'shop');
  db.setSetting(guild, 'level_up_channel_id', 'level-room');
  assert.equal(db.settings(guild).shop_channel_id, 'shop');
  assert.equal(db.settings(guild).level_up_channel_id, 'level-room');
  const adminCoins = db.addCoins(guild, user, 75);
  assert.equal(adminCoins.coins, 76);
  db.setRole(guild, 'text', 5, 'role');
  assert.equal(db.roles(guild, 'text')[0].role_id, 'role');
  db.saveInviteSnapshots(guild, [{ code: 'personal-code', inviterId: 'inviter-test', uses: 0, maxUses: 0 }]);
  assert.equal(db.inviteSnapshots(guild)[0].code, 'personal-code');
  assert.equal(db.recordInviteJoin(guild, 'joined-test', 'inviter-test', 'personal-code'), true);
  assert.equal(db.recordInviteJoin(guild, 'joined-test', 'inviter-test', 'personal-code'), false);
  assert.equal(db.inviteCount(guild, 'inviter-test'), 1);
  db.addXp(guild, user, 'text', 12, { message: true });
  db.startVoice(guild, user, 1000);
  const reset = db.resetMember(guild, user);
  assert.equal(reset.coins, 0);
  assert.equal(reset.total_xp, 0);
  assert.equal(reset.text_xp, 0);
  assert.equal(reset.voice_xp, 0);
  assert.equal(reset.messages, 0);
  assert.ok(db.voice(guild, user).started_at > 1000, 'an active voice session is retained but restarted');
  assert.equal(db.leaderboard(guild, 'text', 'daily').length, 0);
  assert.equal(db.inviteCount(guild, 'inviter-test'), 1);
  db.close();
  console.log('Smoke test passed.');
} finally {
  fs.rmSync(dir, { recursive: true, force: true });
}
