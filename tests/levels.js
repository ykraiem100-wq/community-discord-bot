'use strict';
const assert = require('node:assert/strict');
const { DEFAULT_CURVE, xpToNextLevel, xpToReachLevel, levelProgress, difficultyFor } = require('../src/levels');
assert.equal(xpToNextLevel(0),100);
assert.equal(xpToNextLevel(49),296);
assert.equal(xpToNextLevel(50),300);
assert.equal(xpToNextLevel(99),790);
assert.equal(xpToNextLevel(100),800);
assert.equal(xpToReachLevel(50),9900);
assert.equal(xpToReachLevel(100),37150);
assert.equal(levelProgress(9900).level,50);
assert.equal(levelProgress(37150).level,100);
assert.equal(difficultyFor(20),'سهل ← متوسط');
assert.equal(difficultyFor(75),'متوسط ← صعب');
assert.equal(difficultyFor(50),'سهل ← متوسط');
assert.equal(difficultyFor(100),'متوسط ← صعب');
assert.equal(difficultyFor(101),'صعب');
const adjusted = { ...DEFAULT_CURVE, easyBase: 120, easyStep: 5 };
assert.equal(xpToNextLevel(0,adjusted),120);
console.log('Level curve tests passed.');
