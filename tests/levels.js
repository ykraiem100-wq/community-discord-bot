'use strict';
const assert = require('node:assert/strict');
const { DEFAULT_CURVE, xpToNextLevel, xpToReachLevel, levelProgress, difficultyFor } = require('../src/levels');
assert.equal(xpToNextLevel(0),120);
assert.equal(xpToNextLevel(49),512);
assert.equal(xpToNextLevel(50),650);
assert.equal(xpToNextLevel(99),1826);
assert.equal(xpToNextLevel(100),2200);
assert.equal(xpToReachLevel(50),15800);
assert.equal(xpToReachLevel(100),77700);
assert.equal(levelProgress(15800).level,50);
assert.equal(levelProgress(77700).level,100);
assert.equal(difficultyFor(20),'سهل ← متوسط');
assert.equal(difficultyFor(75),'متوسط ← صعب');
assert.equal(difficultyFor(50),'سهل ← متوسط');
assert.equal(difficultyFor(100),'متوسط ← صعب');
assert.equal(difficultyFor(101),'صعب');
const adjusted = { ...DEFAULT_CURVE, easyBase: 140, easyStep: 5 };
assert.equal(xpToNextLevel(0,adjusted),140);
console.log('Level curve tests passed.');
