'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { DEFAULT_MEMBER_WELCOME_TEXT, normalizeMemberWelcomeTemplate, formatMemberWelcomeText } = require('../src/member-welcome-text');
const read = (file) => fs.readFileSync(path.join(__dirname, '..', file), 'utf8');
const member = { id: '123456789012345678', displayName: 'Yousef', user: { username: 'yousef' }, guild: { name: 'DOS COMMUNITY', memberCount: 42 } };
assert.match(DEFAULT_MEMBER_WELCOME_TEXT, /\{user\}/);
assert.match(DEFAULT_MEMBER_WELCOME_TEXT, /\{memberCount\}/);
assert.equal(normalizeMemberWelcomeTemplate('@everyone مرحباً {user}'), '@\u200beveryone مرحباً {user}');
const text = formatMemberWelcomeText('مرحباً {user} في {server} • رقمك {memberCount} • {username}', member);
assert.equal(text, 'مرحباً <@123456789012345678> في DOS COMMUNITY • رقمك 42 • Yousef');
assert.doesNotMatch(formatMemberWelcomeText('اهلا @here {user}', member), /@here/);
const admin = read('src/admin.js');
const index = read('src/index.js');
const render = read('src/render.js');
assert.match(admin, /value: 'boost_xp'/);
assert.match(admin, /admin:boost-xp:save/);
assert.match(admin, /admin:welcome-card:save/);
assert.match(admin, /member_welcome_enabled/);
assert.match(index, /sendMemberWelcomeCard\(member\)/);
assert.match(index, /getBoosterMultiplier\(message\.member/);
assert.match(index, /applyXpMultiplier\(elapsedMinutes \* voiceRate, multiplier\)/);
assert.match(render, /function renderMemberWelcomeCard\(/);
assert.match(render, /drawCircleImage\(ctx, avatar, 56, 48, 90/);
assert.match(render, /drawText\(ctx, 'Welcome To'/);
assert.match(render, /drawText\(ctx, 'DOS'/);
console.log('Member welcome card and controls tests passed.');
