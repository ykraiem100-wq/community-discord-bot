'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');
const render = read('src/render.js');
const panels = read('src/panels.js');
const shop = read('src/shop.js');
const admin = read('src/admin.js');
const index = read('src/index.js');
assert.ok(fs.existsSync(path.join(root, 'assets/templates/shop-crest-bg.png')));
assert.ok(fs.existsSync(path.join(root, 'assets/templates/shop-title-overlay.png')));
assert.match(render, /renderShopHeader\(guild = null\)/);
assert.match(render, /shop-title-overlay\.png/);
assert.match(panels, /attachment:\/\/dos-main-panel\.png/);
assert.match(panels, /attachment:\/\/dos-notifications\.png/);
assert.match(shop, /attachment:\/\/dos-credits-shop\.png/);
assert.match(admin, /attachment:\/\/dos-admin-section\.png/);
assert.match(admin, /attachment:\/\/dos-admin-dashboard\.png/);
assert.match(index, /attachment:\/\/dos-commands\.png/);
assert.match(index, /helpPayload\(\)/);
assert.doesNotMatch(`${render}\n${panels}\n${shop}\n${admin}\n${index}`, /SXP/);
console.log('DOS UI attachment, image, command-list and no-extra-XP-feature checks passed.');
